#!/usr/bin/env node
// Mirrors every canonical src/schemas/<vertical>/<tool>.json file into a
// generated src/generated/<vertical>/<tool>.ts file exporting the same data
// as an `as const` literal. Plain `import data from './x.json'` widens
// string/number properties (verified empirically — see ADR 0001), which
// breaks json-schema-to-ts's FromSchema. This mechanical mirror exists
// purely to give TypeScript the literal types FromSchema needs; the JSON
// files remain the sole authored source of truth. Contributors never touch
// this directory by hand — it's gitignored and regenerated on every
// pretest/prebuild/pretypecheck.

import { readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const schemasDir = path.join(here, '..', 'src', 'schemas');
const generatedDir = path.join(here, '..', 'src', 'generated');

async function main() {
  await rm(generatedDir, { recursive: true, force: true });

  const entries = await readdir(schemasDir, { withFileTypes: true });
  const verticals = entries.filter((entry) => entry.isDirectory());

  for (const vertical of verticals) {
    const verticalDir = path.join(schemasDir, vertical.name);
    const outDir = path.join(generatedDir, vertical.name);
    await mkdir(outDir, { recursive: true });

    const files = await readdir(verticalDir);
    for (const file of files) {
      if (!file.endsWith('.json') || file.endsWith('.example.json')) continue;

      const toolName = file.replace(/\.json$/, '');
      const raw = await readFile(path.join(verticalDir, file), 'utf8');
      const data = JSON.parse(raw);

      const ts =
        `// AUTO-GENERATED by scripts/generate-ts-mirrors.mjs — do not edit.\n` +
        `// Source of truth: src/schemas/${vertical.name}/${file}\n` +
        `const tool = ${JSON.stringify(data, null, 2)} as const;\n\n` +
        `export default tool;\n`;

      await writeFile(path.join(outDir, `${toolName}.ts`), ts, 'utf8');
    }
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
